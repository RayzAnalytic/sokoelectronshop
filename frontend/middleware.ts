import { NextResponse } from "next/server";
import type { NextRequest } from "next/server";

const DJANGO_BACKEND_URL = process.env.DJANGO_BACKEND_URL!;
const ADMIN_PATH_SECRET = process.env.ADMIN_PATH_SECRET ?? "ops-7f3k9z";
const ADMIN_BASIC_USER = process.env.ADMIN_BASIC_USER!;
const ADMIN_BASIC_PASS = process.env.ADMIN_BASIC_PASS!;

function unauthorized() {
    return new NextResponse("Authentication required", {
        status: 401,
        headers: {
            "WWW-Authenticate": 'Basic realm="Restricted Area", charset="UTF-8"',
        },
    });
}

function proxyTo(pathname: string, request: NextRequest) {
    const backend = new URL(DJANGO_BACKEND_URL);
    const url = request.nextUrl.clone();
    url.protocol = backend.protocol;
    url.host = backend.host;
    url.pathname = pathname;
    return NextResponse.rewrite(url);
}

function checkBasicAuth(request: NextRequest): boolean {
    const header = request.headers.get("authorization");
    if (!header?.startsWith("Basic ")) return false;
    try {
        const decoded = atob(header.slice(6));
        const idx = decoded.indexOf(":");
        const user = decoded.slice(0, idx);
        const pass = decoded.slice(idx + 1);
        return user === ADMIN_BASIC_USER && pass === ADMIN_BASIC_PASS;
    } catch {
        return false;
    }
}

export function middleware(request: NextRequest) {
    const { pathname } = request.nextUrl;

    // Any path that points at the Django admin (either the friendly /admin
    // or the real secret path generated by Django).
    const isAdminRoute =
        pathname === "/admin" ||
        pathname.startsWith("/admin/") ||
        pathname === `/${ADMIN_PATH_SECRET}` ||
        pathname.startsWith(`/${ADMIN_PATH_SECRET}/`);

    if (isAdminRoute) {
        if (!checkBasicAuth(request)) return unauthorized();

        // Friendly /admin -> rewrite to Django's real admin path
        if (pathname === "/admin" || pathname.startsWith("/admin/")) {
            const newPath = pathname.replace(/^\/admin/, `/${ADMIN_PATH_SECRET}`);
            return proxyTo(newPath, request);
        }
        // Already on the secret path -> pass through
        return proxyTo(pathname, request);
    }

    // Anything else that needs to hit Django
    if (
        pathname.startsWith("/api/") ||
        pathname.startsWith("/static/") ||
        pathname.startsWith("/media/")
    ) {
        return proxyTo(pathname, request);
    }

    return NextResponse.next();
}

export const config = {
    // Catch everything except Next.js internals + favicon.
    // This is required because ADMIN_PATH_SECRET is dynamic (env var)
    // and matcher is a static export — so we filter inside middleware.
    matcher: ["/((?!_next/static|_next/image|favicon.ico).*)"],
};